/**
 * Regenerate middleware/supabase/parts/seed.sql from store/seed-data.js
 * (the master data taken from the "Data List" Excel workbooks).
 *
 * Usage:  node tools/build-seed-sql.js
 * Then:   python3 tools/build-setup-sql.py     (rebuilds the single setup file)
 *
 * Product photos are deliberately NOT written here — the middleware serves
 * them from store/item-images.js, which keeps this file small enough for the
 * Supabase SQL editor.
 */
const fs = require("fs");
const path = require("path");
const seed = require("../store/seed-data");

const esc = s => String(s).replace(/'/g, "''");
const j = o => "'" + esc(JSON.stringify(o)) + "'::jsonb";
const out = [];

out.push("-- ═══════════════════════════════════════════════════════════════════");
out.push("-- PROSAFE × EGA — master data (SRS2 25-08-26, from the Data List workbooks)");
out.push("-- Generated by middleware/tools/build-seed-sql.js — do not edit by hand.");
out.push("-- Upserts by primary key, so re-running only refreshes master data.");
out.push("-- ═══════════════════════════════════════════════════════════════════");
out.push("");

const kinds = [
  ["customers", seed.customers, "id"],
  ["employees", seed.employees, "empId"],
  ["contracts", seed.contracts, "ref"],
  ["departments", seed.departments, "code"],
  ["locations", seed.locations, "code"],
  ["divisions", seed.divisions, "code"],
  ["stores", seed.stores, "code"],
  ["items", seed.items, "code"],
  ["priceLists", seed.priceLists, "id"]
];

/* The Group and Category masters were removed (Sept-26): the grouping now
   lives on the item itself, so clear the old rows from an existing database. */
out.push("-- the Group and Category masters were removed — the item carries the");
out.push("-- grouping now, so drop any rows left over from an earlier setup");
out.push("delete from masters where kind in ('groups', 'categories');");
out.push("");
out.push("-- masters");
for (const [kind, list, key] of kinds)
  for (const rec of list)
    out.push(`insert into masters (kind, id, data) values ('${kind}', '${esc(rec[key])}', ${j(rec)}) on conflict (kind, id) do update set data = excluded.data;`);
for (const u of seed.uoms)
  out.push(`insert into masters (kind, id, data) values ('uoms', '${esc(u)}', '"${esc(u)}"'::jsonb) on conflict (kind, id) do update set data = excluded.data;`);

out.push("");
out.push("-- opening inventory — inserted once; live quantities are never overwritten");
for (const [store, items] of Object.entries(seed.inventory))
  for (const [code, qty] of Object.entries(items))
    out.push(`insert into inventory (store_code, item_code, qty) values ('${store}', '${code}', ${qty}) on conflict (store_code, item_code) do nothing;`);

out.push("");
out.push("-- document sequences — inserted once, never reset");
for (const [k, v] of Object.entries(seed.seq))
  out.push(`insert into seqs (key, val) values ('${k}', ${v}) on conflict (key) do nothing;`);

out.push("");
out.push("-- NOTE: no demo users in Supabase mode — people sign up in the apps and");
out.push("-- the admin (ADMIN_EMAILS) assigns role, price lists and stores.");

const file = path.join(__dirname, "..", "supabase", "parts", "seed.sql");
const text = out.join("\n") + "\n";
fs.writeFileSync(file, text);
console.log(`wrote supabase/parts/seed.sql — ${Math.round(text.length / 1024)} KB, ${out.length} statements/lines`);
